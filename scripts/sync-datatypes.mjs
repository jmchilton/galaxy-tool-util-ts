#!/usr/bin/env node
// Snapshot a Galaxy server's datatype hierarchy into @galaxy-tool-util/workflow-graph.
// Usage: node scripts/sync-datatypes.mjs [--galaxy-url URL]   (default https://usegalaxy.org)
//        node scripts/sync-datatypes.mjs --check              (offline: verify the .sha256)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import * as prettier from "prettier";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DST = join(ROOT, "packages/workflow-graph/src/datatypes-snapshot.generated.ts");
const SHA_FILE = DST + ".sha256";
// The client's query; the default upload_only=true omits non-upload types.
const PATH = "/api/datatypes/types_and_mapping?upload_only=false";

const { values } = parseArgs({
  options: {
    "galaxy-url": { type: "string", default: "https://usegalaxy.org" },
    check: { type: "boolean", default: false },
  },
});

function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function check() {
  const rel = relative(ROOT, SHA_FILE);
  if (!existsSync(SHA_FILE)) {
    console.error(`FAIL: ${rel} missing — run make sync-datatypes.`);
    process.exit(1);
  }
  const expected = readFileSync(SHA_FILE, "utf-8").trim().split(/\s+/)[0];
  const actual = sha256(readFileSync(DST));
  if (actual !== expected) {
    console.error(
      `FAIL datatypes snapshot checksum:\n  expected ${expected}\n  actual   ${actual}\nRe-run make sync-datatypes.`,
    );
    process.exit(1);
  }
  console.log("datatypes snapshot: checksum OK.");
}

// Galaxy builds these maps from Python sets; sort keys so re-syncs diff only on real changes.
function sortKeys(record) {
  return Object.fromEntries(
    Object.keys(record)
      .sort()
      .map((k) => [k, record[k]]),
  );
}

async function sync(galaxyUrl) {
  async function getJson(path) {
    const response = await fetch(galaxyUrl + path, { signal: AbortSignal.timeout(60_000) });
    if (!response.ok) throw new Error(`GET ${galaxyUrl}${path}: HTTP ${response.status}`);
    return response.json();
  }

  const [version, raw] = await Promise.all([getJson("/api/version"), getJson(PATH)]);
  const { ext_to_class_name, class_to_classes } = raw.datatypes_mapping ?? {};
  if (
    !Array.isArray(raw.datatypes) ||
    raw.datatypes.length === 0 ||
    !ext_to_class_name ||
    !class_to_classes
  ) {
    throw new Error(`Unexpected ${PATH} response from ${galaxyUrl}.`);
  }
  for (const ext of raw.datatypes) {
    const cls = ext_to_class_name[ext];
    if (!cls || !class_to_classes[cls]) throw new Error(`Datatype '${ext}' has no class mapping.`);
  }
  const sortedClasses = Object.entries(class_to_classes).map(([cls, m]) => [cls, sortKeys(m)]);
  const typesAndMapping = {
    datatypes: raw.datatypes,
    datatypes_mapping: {
      ext_to_class_name: sortKeys(ext_to_class_name),
      class_to_classes: sortKeys(Object.fromEntries(sortedClasses)),
    },
  };
  const source = {
    galaxyUrl,
    path: PATH,
    versionMajor: version.version_major,
    versionMinor: version.version_minor,
    fetchedAt: new Date().toISOString().slice(0, 10),
  };

  const body = `// Generated by make sync-datatypes. Do not edit.
import type { DatatypesCombinedMap } from "./datatypes-combined-map.js";

export const DATATYPES_SNAPSHOT: {
  source: {
    galaxyUrl: string;
    path: string;
    versionMajor: string;
    versionMinor: string;
    fetchedAt: string;
  };
  typesAndMapping: DatatypesCombinedMap;
} = ${JSON.stringify({ source, typesAndMapping })};
`;
  const config = await prettier.resolveConfig(DST);
  const formatted = await prettier.format(body, { ...config, filepath: DST });
  writeFileSync(DST, formatted);
  writeFileSync(SHA_FILE, `${sha256(formatted)}  datatypes-snapshot.generated.ts\n`);
  console.log(
    `Wrote ${typesAndMapping.datatypes.length} datatypes from ${galaxyUrl} (${source.versionMajor}.${source.versionMinor}).`,
  );
}

if (values.check) {
  check();
} else {
  await sync(values["galaxy-url"].replace(/\/+$/, ""));
}
